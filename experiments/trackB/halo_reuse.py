#!/usr/bin/env python3
"""
P3, step 1 (docs/trackB_storage_layout.md §6): how much of Phase 3's halo I/O a reuse-aware layout saves, with identical
per-unit inputs. Reads only the Track A caches (halo.npy, meta.json).

Phase 2 materializes the 1-hop halo once per unit: a boundary vertex in r units' halos is stored and read r times.
Hybrid layout: vertices with reuse r <= tau stay replicated in the units' partitions, and the rest go to one shared "hot"
table that each of the B readers (executors) loads once and caches. A hot vertex then costs B reads and one stored row
instead of r. So reads are minimal at tau = B, a rule known before Phase 2 writes. Storage is minimal at tau = 1.
Rows are counted. Bytes = rows x (8 + 4 f), the Track A estimate.

    python experiments/trackB/halo_reuse.py --store //wsl.localhost/Ubuntu-24.04/home/btan4/lakegrl/store
"""
import argparse
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "results", "trackB")
READERS = [1, 2, 4, 8, 16, 32]


def hybrid(r, members, tau, B):
    """(rows read, rows stored) by Phase 3 when halo vertices with reuse > tau are shared by B readers."""
    hot = r > tau
    rep = int(r[~hot].sum())
    return members + rep + B * int(hot.sum()), members + rep + int(hot.sum())


def analyse(cache):
    meta = json.load(open(os.path.join(cache, "meta.json")))
    _, r = np.unique(np.load(os.path.join(cache, "halo.npy"))[0], return_counts=True)
    M, H = meta["n_members"], int(r.sum())
    full = M + H
    out = {"dataset": meta["dataset"], "alg": meta["alg"], "units": meta["n_units"], "members": M, "halo_rows": H,
           "boundary_vertices": len(r), "feat_dim": meta["feat_dim"],
           "reuse_p50_p90_p99_max": np.percentile(r, [50, 90, 99, 100]).tolist(), "by_readers": {}}
    for B in READERS:
        read, stored = hybrid(r, M, B, B)
        # tau = B is read-optimal: a hot vertex costs B reads, a replicated one r
        assert read == min(hybrid(r, M, t, B)[0] for t in range(0, int(r.max()) + 1)), B
        out["by_readers"][B] = {"hot_vertices": int((r > B).sum()), "hot_share_of_halo_rows": float(r[r > B].sum() / H),
                                "read_vs_full_halo": read / full, "stored_vs_full_halo": stored / full}
    out["stage3a_vs_full_halo"] = M / full
    return out


def markdown(rows):
    out = ["| dataset | units | halo / members | reuse p50 / p90 / max | Stage 3a | " +
           " | ".join(f"B = {B}" for B in READERS) + " |", "|---" * (5 + len(READERS)) + "|"]
    for a in rows:
        q = a["reuse_p50_p90_p99_max"]
        out.append(f"| {a['dataset']} | {a['units']} | {a['halo_rows'] / a['members']:.2f}× | {q[0]:g} / {q[1]:g} / "
                   f"{q[3]:g} | {a['stage3a_vs_full_halo']:.2f} | " + " | ".join(
                       f"{b['read_vs_full_halo']:.2f} / {b['stored_vs_full_halo']:.2f}" for b in a["by_readers"].values())
                   + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--store", default=os.path.expanduser("~/lakegrl/store"))
    ap.add_argument("--datasets", nargs="+", default=["ogbn-arxiv-lp", "reddit-lp", "ogbn-products-lp"])
    ap.add_argument("--alg", default="louvain")
    args = ap.parse_args()
    rows = [analyse(os.path.join(args.store, ds, f"trackA_{args.alg}")) for ds in args.datasets]
    with open(os.path.join(RES, "P3_halo_reuse.jsonl"), "a") as fh:
        for a in rows:
            fh.write(json.dumps(a) + "\n")
    md = ("Rows read / stored by Phase 3 relative to the full materialized halo (members + halo rows), hybrid layout "
          "with tau = B; Stage 3a = members only.\n\n" + markdown(rows))
    with open(os.path.join(RES, "P3_halo_reuse.md"), "w", encoding="utf-8") as fh:
        fh.write("# P3 halo reuse (generated by experiments/trackB/halo_reuse.py)\n\n" + md + "\n")
    print(md.encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
